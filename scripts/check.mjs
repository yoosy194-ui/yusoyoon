import {readFile,readdir} from 'node:fs/promises';
import {strict as assert} from 'node:assert';
import {Script} from 'node:vm';
import {build} from './build.mjs';
const d=JSON.parse(await readFile(new URL('../src/data/portfolio.json',import.meta.url),'utf8'));
for(const k of ['name','englishName','intro','bio','phone','email','school','major','photo'])assert.equal(typeof d[k],'string',`${k} must be a string`);
for(const k of ['skills','careers','works'])assert(Array.isArray(d[k]),`${k} must be an array`);
for(const w of d.works)for(const k of ['title','category','year','description'])assert.equal(typeof w[k],'string',`work.${k} must be a string`);
new Script(await readFile(new URL('../src/scripts/main.js',import.meta.url),'utf8'));
const editor=await readFile(new URL('../tools/editor.html',import.meta.url),'utf8');
for(const m of editor.matchAll(/<script>([\s\S]*?)<\/script>/g))new Script(m[1]);
await build();
const files=await readdir(new URL('../dist/',import.meta.url));
assert(!files.includes('editor.html'),'Editor must never be deployed');
const publicHtml=await readFile(new URL('../dist/index.html',import.meta.url),'utf8');
assert(!publicHtml.includes('__PORTFOLIO_DATA__'));
assert(publicHtml.includes('id="portfolio-data"'));
for(const id of ['about','experience','work','contact','detail'])assert(publicHtml.includes(`id="${id}"`));
const standalone=await readFile(new URL('../dist/portfolio.html',import.meta.url),'utf8');
assert(!standalone.includes('src="./scripts/main.js"'));
assert(!standalone.includes('href="./styles/main.css"'));
console.log('Passed: data structure, JavaScript syntax, build, public section links, editor exclusion, standalone export.');
